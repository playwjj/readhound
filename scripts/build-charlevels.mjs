// Builds src/data/charlevels.js from two public datasets shipped in the
// `hanzi` npm package (dev dependency):
//   - 通用规范汉字表 (2013), level 1 = the 3500 common characters
//   - Jun Da's Modern Chinese character frequency list
// Output: the 3500 level-1 characters ordered by corpus frequency.
// A character's rank in that string is its "level": primary-school
// textbooks introduce roughly 1600 characters by end of grade 2, 2500 by
// grade 4 and 3000 by grade 6, so frequency rank is used as a proxy for
// the grade a child normally meets the character. Parents can override
// with the actual textbook lists (see /parent → 课本生字).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const dataDir = require.resolve("hanzi/package.json").replace(/package\.json$/, "lib/data/");

const tgh = readFileSync(dataDir + "tongyong-guifan-2013.txt", "utf8")
  .split("\n").filter((l) => l && !l.startsWith("#"))
  .map((l) => l.split("\t")).filter(([, n]) => Number(n) <= 3500).map(([c]) => c);
const level1 = new Set(tgh);

const junda = require(dataDir + "frequencyjunda.txt.js");
const rankOf = new Map();
for (const line of junda.split("\n")) {
  const [rank, ch] = line.split("\t");
  if (ch && !rankOf.has(ch)) rankOf.set(ch, Number(rank));
}
const ordered = [...level1].sort((a, b) =>
  (rankOf.get(a) ?? 1e6 + tgh.indexOf(a)) - (rankOf.get(b) ?? 1e6 + tgh.indexOf(b)));
if (ordered.length !== 3500) throw new Error("expected 3500, got " + ordered.length);

const out = `// GENERATED by scripts/build-charlevels.mjs — do not edit.
// 通用规范汉字表 level-1 (3500 chars), ordered by Jun Da corpus frequency.
export const CHARS_BY_FREQ = ${JSON.stringify(ordered.join(""))};
`;
writeFileSync(new URL("../src/data/charlevels.js", import.meta.url), out);
console.log("wrote", ordered.length, "chars; first 40:", ordered.slice(0, 40).join(""));
console.log("ranks 2400-2440:", ordered.slice(2400, 2440).join(""));
