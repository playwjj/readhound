#!/usr/bin/env python3
"""Build src/data/textbook.js from the 统编版 (MOE) textbook character database.

Source: Zhang, M., Guo, T. et al. (2023). A large-scale database of Chinese
characters and words collected from elementary school textbooks.
Behavior Research Methods. Data: https://osf.io/ynk8c/ (Character.xlsx)

Columns used: Char, Volume (1-12 = 一上 … 六下), RW (1 = 识字表 recognise,
2 = 写字表 write). Grade is derived from Volume (the Grade column has one
inconsistent row: 勿, grade 1 / volume 10).

Output, per volume: the characters first *recognised* in that volume (a
character required to be written is also recognised) and the characters
first required to be *written*.

Usage:
  curl -L -o /tmp/Character.xlsx https://osf.io/download/prjsc/
  python3 -I scripts/build-textbook.py /tmp/Character.xlsx
Stdlib only (zipfile + xml), no third-party packages.
"""
import json
import re
import sys
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}


def col_index(ref):
    letters = re.match(r"[A-Z]+", ref).group(0)
    n = 0
    for ch in letters:
        n = n * 26 + ord(ch) - 64
    return n - 1


def read_sheet(path, name):
    with zipfile.ZipFile(path) as z:
        shared = []
        if "xl/sharedStrings.xml" in z.namelist():
            for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS):
                shared.append("".join(t.text or "" for t in si.iter("{%s}t" % NS["m"])))
        wb = ET.fromstring(z.read("xl/workbook.xml"))
        rels = ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))
        rid = next(s.get("{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id")
                   for s in wb.find("m:sheets", NS) if s.get("name") == name)
        target = next(r.get("Target") for r in rels if r.get("Id") == rid)
        sheet = ET.fromstring(z.read("xl/" + target.lstrip("/").removeprefix("xl/")))
        for row in sheet.find("m:sheetData", NS):
            out = {}
            for c in row:
                v = c.find("m:v", NS)
                if v is None:
                    is_ = c.find("m:is", NS)
                    val = "".join(t.text or "" for t in is_.iter("{%s}t" % NS["m"])) if is_ is not None else None
                else:
                    val = shared[int(v.text)] if c.get("t") == "s" else v.text
                out[col_index(c.get("r"))] = val
            yield [out.get(i) for i in range(max(out) + 1)] if out else []


def main(path):
    rows = read_sheet(path, "Data")
    header = next(rows)
    ci, vi, rwi = header.index("Char"), header.index("Volume"), header.index("RW")
    recog, write = {}, {}
    for r in rows:
        if len(r) <= rwi or not r[ci]:
            continue
        ch, vol, rw = r[ci].strip(), int(float(r[vi])), int(float(r[rwi]))
        recog[ch] = min(recog.get(ch, 99), vol)
        if rw == 2:
            write[ch] = min(write.get(ch, 99), vol)
    by_vol = lambda d: ["".join(sorted((c for c, v in d.items() if v == vol), key=ord)) for vol in range(1, 13)]
    out = Path(__file__).resolve().parent.parent / "src" / "data" / "textbook.js"
    out.write_text(
        "// GENERATED by scripts/build-textbook.py — do not edit.\n"
        "// 统编版 primary Chinese textbooks, per volume (index 0 = 一年级上册 … 11 = 六年级下册).\n"
        "// Source: Zhang, Guo et al. (2023), Behavior Research Methods, https://osf.io/ynk8c/\n"
        "// RECOGNISE[v]: characters first required to be recognised (识字表) in volume v+1.\n"
        "// WRITE[v]: characters first required to be written (写字表) in volume v+1.\n"
        f"export const RECOGNISE = {json.dumps(by_vol(recog), ensure_ascii=False, indent=1)};\n"
        f"export const WRITE = {json.dumps(by_vol(write), ensure_ascii=False, indent=1)};\n",
        encoding="utf-8",
    )
    cum = 0
    for v, s in enumerate(by_vol(recog), 1):
        cum += len(s)
        print(f"vol {v:2}: recognise +{len(s):3} (cum {cum:4}), write +{len(by_vol(write)[v-1]):3}")
    print("wrote", out)


if __name__ == "__main__":
    main(sys.argv[1])
